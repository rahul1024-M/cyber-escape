export const NEXUS_BOSS_HEALTH = NEXUS_CHALLENGES.length;

export function createInitialBossState(): BossEncounterState {
  return { phase: "reconnaissance", bossHealth: NEXUS_BOSS_HEALTH };
}

export function recordBossDecision(
  state: BossEncounterState,
  correct: boolean,
): BossEncounterState {
  return correct
    ? { ...state, bossHealth: Math.max(0, state.bossHealth - 1) }
    : state;
}

export function transitionBossPhase(
  state: BossEncounterState,
  nextChallenge: Challenge | undefined,
): BossEncounterState {
  return nextChallenge?.bossPhase
    ? { ...state, phase: nextChallenge.bossPhase }
    : state;
}

export function canBuyNexusHint(hintsUsed: number): boolean {
  return isNexusHintCountValid(hintsUsed) && hintsUsed < 3;
}

export function isNexusHintCountValid(hintsUsed: unknown): hintsUsed is number {
  return typeof hintsUsed === "number" &&
    Number.isInteger(hintsUsed) &&
    hintsUsed >= 0 &&
    hintsUsed <= 3;
}

export function applyHealthPenalty(health: number): number {
  return health - 1;
}

export function isBossPhaseId(value: unknown): value is BossPhaseId {
  return value === "reconnaissance" || value === "containment" || value === "recovery";
}

export function isBossEncounterStateValid(
  value: unknown,
  challenge: Challenge | undefined,
  expectedHealth: number,
): value is BossEncounterState {
  if (!value || typeof value !== "object" || Array.isArray(value) || !challenge?.bossPhase) return false;
  const state = value as Record<string, unknown>;
  const bossHealth = state["bossHealth"];
  return (
    isBossPhaseId(state["phase"]) &&
    state["phase"] === challenge.bossPhase &&
    typeof bossHealth === "number" &&
    Number.isInteger(bossHealth) &&
    bossHealth === expectedHealth &&
    expectedHealth >= 0 &&
    expectedHealth <= NEXUS_BOSS_HEALTH
  );
}
